BEGIN;

CREATE TABLE matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES tournament_stages (id),
    home_tournament_team_id BIGINT NOT NULL REFERENCES teams (id),
    away_tournament_team_id BIGINT NOT NULL REFERENCES teams (id),
    home_score SMALLINT CHECK (home_score >= 0),
    away_score SMALLINT CHECK (away_score >= 0),
    scheduled_start_at TIMESTAMP(6) NOT NULL,
    prediction_lock_at TIMESTAMP(6) NOT NULL,
    actual_start_at TIMESTAMP(6),
    finished_at TIMESTAMP(6),
    status VARCHAR(20) NOT NULL DEFAULT 'scheduled' CHECK (
        status IN (
            'scheduled',
            'live',
            'finished',
            'postponed',
            'cancelled'
        )
    ),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_matches_different_teams CHECK (
        home_tournament_team_id <> away_tournament_team_id
    )
);

CREATE INDEX idx_matches_stage_scheduled_start ON matches (stage_id, scheduled_start_at);
CREATE INDEX idx_matches_home_team_scheduled_start ON matches (home_tournament_team_id, scheduled_start_at);
CREATE INDEX idx_matches_away_team_scheduled_start ON matches (away_tournament_team_id, scheduled_start_at);
CREATE INDEX idx_matches_status_scheduled_start ON matches (status, scheduled_start_at);
CREATE INDEX idx_matches_scheduled_start_at ON matches (scheduled_start_at);

COMMIT;
