BEGIN;

CREATE TABLE predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT NOT NULL REFERENCES tournament_participants (id),
    match_id BIGINT NOT NULL REFERENCES matches (id),
    home_score SMALLINT NOT NULL CHECK (home_score >= 0),
    away_score SMALLINT NOT NULL CHECK (away_score >= 0),
    result_type VARCHAR(20) CHECK (
        result_type IN (
            'exact_score',
            'outcome',
            'missed'
        )
    ),
    awarded_points SMALLINT CHECK (awarded_points >= 0),
    calculated_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_predictions_participant_match UNIQUE (participant_id, match_id)
);

CREATE INDEX idx_predictions_match_id ON predictions (match_id);

COMMIT;
